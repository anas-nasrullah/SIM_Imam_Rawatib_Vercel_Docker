-- SIM Imam Rawatib Lengkap: MySQL 8 / MariaDB 10.4+
-- Database terpisah dari proyek versi awal, agar tidak menimpa data lama.
CREATE DATABASE IF NOT EXISTS `sim_imam_rawatib_lengkap` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `sim_imam_rawatib_lengkap`;

CREATE TABLE IF NOT EXISTS imams (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT,
 name VARCHAR(120) NOT NULL, phone VARCHAR(30) DEFAULT NULL, email VARCHAR(190) DEFAULT NULL,
 active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT,
 name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('admin','pengurus','imam') NOT NULL,
 imam_id INT UNSIGNED DEFAULT NULL,
 active TINYINT(1) NOT NULL DEFAULT 1, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(id), UNIQUE KEY uq_email(email), UNIQUE KEY uq_imam_login(imam_id),
 FOREIGN KEY (imam_id) REFERENCES imams(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS settings (
 `key` VARCHAR(90) NOT NULL PRIMARY KEY,
 `value` TEXT NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS schedules (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT,
 prayer_date DATE NOT NULL,
 prayer ENUM('Subuh','Dzuhur','Ashar','Maghrib','Isya') NOT NULL,
 imam_id INT UNSIGNED NOT NULL,
 start_time TIME NOT NULL,
 is_extra TINYINT(1) NOT NULL DEFAULT 0,
 confirmation ENUM('pending','bisa','tidak_bisa') NOT NULL DEFAULT 'pending',
 confirmation_at DATETIME DEFAULT NULL,
 confirmation_note VARCHAR(255) DEFAULT NULL,
 attendance ENUM('belum','hadir','izin','tidak_hadir') NOT NULL DEFAULT 'belum',
 attendance_at DATETIME DEFAULT NULL,
 created_by INT UNSIGNED DEFAULT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(id), UNIQUE KEY uq_slot(prayer_date,prayer), KEY idx_imam_date(imam_id,prayer_date),
 FOREIGN KEY(imam_id) REFERENCES imams(id) ON DELETE RESTRICT,
 FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS schedule_refusals (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT,
 schedule_id INT UNSIGNED NOT NULL, imam_id INT UNSIGNED NOT NULL,
 prayer_date DATE NOT NULL, prayer VARCHAR(12) NOT NULL,
 note VARCHAR(255) DEFAULT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(id), UNIQUE KEY uq_refused_assignment(schedule_id,imam_id),
 KEY idx_refused_imam_date(imam_id,prayer_date),
 FOREIGN KEY(imam_id) REFERENCES imams(id) ON DELETE RESTRICT
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS honor_adjustments (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT, imam_id INT UNSIGNED NOT NULL,
 month DATE NOT NULL, kind ENUM('tambahan','potongan') NOT NULL,
 amount BIGINT UNSIGNED NOT NULL, note VARCHAR(255) NOT NULL,
 created_by INT UNSIGNED DEFAULT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(id), KEY idx_adj_month(month,imam_id),
 FOREIGN KEY(imam_id) REFERENCES imams(id) ON DELETE RESTRICT,
 FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS honor_payments (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT, imam_id INT UNSIGNED NOT NULL,
 month DATE NOT NULL, amount BIGINT UNSIGNED NOT NULL,
 paid_at DATETIME NOT NULL, note VARCHAR(255) DEFAULT NULL,
 created_by INT UNSIGNED DEFAULT NULL,
 PRIMARY KEY(id), KEY idx_pay_month(month,imam_id),
 FOREIGN KEY(imam_id) REFERENCES imams(id) ON DELETE RESTRICT,
 FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT, user_id INT UNSIGNED DEFAULT NULL,
 action VARCHAR(100) NOT NULL, detail VARCHAR(500) DEFAULT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(id), KEY idx_action_date(created_at),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

